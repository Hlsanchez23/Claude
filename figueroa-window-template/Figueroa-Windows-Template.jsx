    function findFont(names) {
        for (var i = 0; i < names.length; i++) {
            try {
                return app.textFonts.getByName(names[i]);
            } catch (e) {
                // try the next one
            }
        }
        return null;
    }

    // A global process swatch, so a color can be changed everywhere at once
    // from the Swatches panel. Falls back to a plain CMYK color.
    function swatch(doc, name, c, m, y, k) {
        var cmyk = new CMYKColor();
        cmyk.cyan = c;
        cmyk.magenta = m;
        cmyk.yellow = y;
        cmyk.black = k;
        try {
            var spot = doc.spots.add();
            spot.name = name;
            spot.color = cmyk;
            spot.colorType = ColorModel.PROCESS;
            var color = new SpotColor();
            color.spot = spot;
            color.tint = 100;
            return color;
        } catch (e) {
            return cmyk;
        }
    }

    function addLayer(doc, name) {
        var layer = doc.layers.add();
        layer.name = name;
        return layer;
    }

    function group(parent, name) {
        var g = parent.groupItems.add();
        g.name = name;
        return g;
    }

    // Rectangle in points. style: { fill, stroke, width, dashes }
    function box(parent, left, top, w, h, style, name) {
        var r = parent.pathItems.rectangle(top, left, w, h);
        if (style.fill) {
            r.filled = true;
            r.fillColor = style.fill;
        } else {
            r.filled = false;
        }
        if (style.stroke) {
            r.stroked = true;
            r.strokeColor = style.stroke;
            r.strokeWidth = style.width;
            if (style.dashes) {
                r.strokeDashes = style.dashes;
            }
        } else {
            r.stroked = false;
        }
        if (name) {
            r.name = name;
        }
        return r;
    }

    // Point text; (x, y) is the baseline of the first line, in points.
    // lines, sizes and fonts are parallel arrays - one entry per line.
    function text(parent, x, y, lines, sizes, fonts, color, justification, name) {
        var t = parent.textFrames.pointText([x, y]);
        t.contents = lines.join('\r');
        t.textRange.characterAttributes.fillColor = color;
        t.textRange.paragraphAttributes.justification = justification;
        for (var i = 0; i < lines.length; i++) {
            var attrs = t.paragraphs[i].characterAttributes;
            attrs.size = sizes[i];
            if (fonts[i]) {
                attrs.textFont = fonts[i];
            }
        }
        if (name) {
            t.name = name;
        }
        return t;
    }

    function printPreset() {
        var list = app.startupPresetsList;
        for (var i = 0; i < list.length; i++) {
            if (/print/i.test(list[i])) {
                return list[i];
            }
        }
        return list.length ? list[0] : 'Print';
    }

    function newDocument(w, h, bleed, notes) {
        var preset = new DocumentPreset();
        preset.title = PROJECT + ' - Window Graphics 1-' + SETTINGS.scale;
        preset.width = w;
        preset.height = h;
        preset.units = RulerUnits.Inches;
        preset.colorMode = DocumentColorSpace.CMYK;
        preset.rasterResolution = DocumentRasterResolution.HighResolution;
        preset.numArtboards = 1;
        var bleedSet = true;
        try {
            preset.documentBleedLink = true;
            preset.documentBleedOffsetRect = [bleed, bleed, bleed, bleed];
        } catch (e) {
            bleedSet = false;
        }
        var doc;
        try {
            doc = app.documents.addDocument(printPreset(), preset);
        } catch (e2) {
            doc = app.documents.add(DocumentColorSpace.CMYK, w, h);
            bleedSet = false;
        }
        if (!bleedSet) {
            notes.push('Set the bleed by hand: File > Document Setup > Bleed ' + num(bleed / 72) + ' in (all sides).');
        }
        return doc;
    }

