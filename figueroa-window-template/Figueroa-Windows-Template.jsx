    // ------------------------------------------------------------------
    // Layout - pure geometry in actual inches, origin at the top-left of the
    // wall, y growing downwards. No Illustrator calls in here.
    // ------------------------------------------------------------------
    function computeLayout(rows, s, sill) {
        var V = s.verticalMullion;
        var n = rows.length;
        var r, c, i, k;
        if (n < 1 || n > LETTERS.length) {
            throw new Error('Expected 1 to ' + LETTERS.length + ' rows of panels, found ' + n + '.');
        }

        // Width of each row, and the average position of its vertical mullions,
        // with every row starting at x = 0.
        var widths = [];
        var means = [];
        for (r = 0; r < n; r++) {
            var ws = rows[r][1];
            var x = 0;
            var sum = 0;
            for (c = 0; c < ws.length; c++) {
                x += ws[c];
                if (c < ws.length - 1) {
                    sum += x + V / 2;
                    x += V;
                }
            }
            widths.push(x);
            means.push(ws.length > 1 ? sum / (ws.length - 1) : x / 2);
        }

        // Sideways offset of each row. The rows are not all the same width, so
        // 'mullions' shifts each row until the average of its vertical-mullion
        // positions matches the other rows (the least-squares best fit).
        var mode = String(s.rowAlignment).toLowerCase();
        if (mode !== 'left' && mode !== 'center' && mode !== 'right') {
            mode = 'mullions';
        }
        for (r = 1; r < n; r++) {
            if (mode === 'mullions' && rows[r][1].length !== rows[0][1].length) {
                mode = 'center'; // mullions can only be matched when every row has the same panel count
            }
        }
        var maxWidth = Math.max.apply(null, widths);
        var maxMean = Math.max.apply(null, means);
        var offsets = [];
        var minOffset = Infinity;
        for (r = 0; r < n; r++) {
            var o;
            if (mode === 'left') {
                o = 0;
            } else if (mode === 'right') {
                o = maxWidth - widths[r];
            } else if (mode === 'center') {
                o = (maxWidth - widths[r]) / 2;
            } else {
                o = maxMean - means[r];
            }
            o = Math.round(o * 16) / 16;
            offsets.push(o);
            if (o < minOffset) {
                minOffset = o;
            }
        }

        // Stack the bands top to bottom: row, mullion, row, mullion ...
        var bands = [];
        for (r = 0; r < n; r++) {
            bands.push({ row: r, h: rows[r][0] });
            if (r < n - 1 || sill) {
                bands.push({ row: -1, h: s.horizontalMullion });
            }
        }
        if (!s.firstRowIsTop) {
            bands.reverse();
        }
        var y = 0;
        var rowY = [];
        for (i = 0; i < bands.length; i++) {
            bands[i].y = y;
            if (bands[i].row >= 0) {
                rowY[bands[i].row] = y;
            }
            y += bands[i].h;
        }

        // Panels and the vertical mullions between them
        var rowBoxes = [];
        var panels = [];
        var vertical = [];
        var area = 0;
        for (r = 0; r < n; r++) {
            var h = rows[r][0];
            var ws2 = rows[r][1];
            var px = offsets[r] - minOffset;
            rowBoxes.push({ row: r, letter: LETTERS.charAt(r), x: px, y: rowY[r], w: widths[r], h: h });
            for (c = 0; c < ws2.length; c++) {
                panels.push({ id: LETTERS.charAt(r) + pad2(c + 1), row: r, col: c + 1, x: px, y: rowY[r], w: ws2[c], h: h });
                area += ws2[c] * h;
                px += ws2[c];
                if (c < ws2.length - 1) {
                    vertical.push({ row: r, col: c + 1, x: px, y: rowY[r], w: V, h: h });
                    px += V;
                }
            }
        }

        // Horizontal mullions span the rows directly above and below them
        var horizontal = [];
        for (i = 0; i < bands.length; i++) {
            if (bands[i].row >= 0) {
                continue;
            }
            var left = Infinity;
            var right = -Infinity;
            for (k = i - 1; k <= i + 1; k += 2) {
                if (k >= 0 && k < bands.length && bands[k].row >= 0) {
                    var b = rowBoxes[bands[k].row];
                    left = Math.min(left, b.x);
                    right = Math.max(right, b.x + b.w);
                }
            }
            horizontal.push({ x: left, y: bands[i].y, w: right - left, h: bands[i].h });
        }

        var width = 0;
        for (r = 0; r < n; r++) {
            width = Math.max(width, rowBoxes[r].x + rowBoxes[r].w);
        }
        var rowOrder = [];
        for (i = 0; i < bands.length; i++) {
            if (bands[i].row >= 0) {
                rowOrder.push(bands[i].row);
            }
        }
        return {
            rows: rowBoxes,
            panels: panels,
            vertical: vertical,
            horizontal: horizontal,
            width: width,
            height: y,
            area: area / 144,
            alignment: mode,
            topRow: rowOrder[0],
            bottomRow: rowOrder[rowOrder.length - 1],
            minRowWidth: Math.min.apply(null, widths),
            maxRowWidth: maxWidth
        };
    }

    // Panels whose width jumps away from BOTH the panel above and the panel
    // below in the same column (likely typos in the spreadsheet).
    function findOutliers(rows, tolerance) {
        var out = [];
        var r, c;
        for (r = 1; r < rows.length - 1; r++) {
            var ws = rows[r][1];
            for (c = 0; c < ws.length; c++) {
                if (c >= rows[r - 1][1].length || c >= rows[r + 1][1].length) {
                    continue;
                }
                var above = rows[r - 1][1][c];
                var below = rows[r + 1][1][c];
                var up = ws[c] - above;
                var down = ws[c] - below;
                if (up * down > 0 && Math.abs(up) > tolerance && Math.abs(down) > tolerance) {
                    out.push({ id: LETTERS.charAt(r) + pad2(c + 1), col: c + 1, w: ws[c], above: above, below: below });
                }
            }
        }
        return out;
    }

